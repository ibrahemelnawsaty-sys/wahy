<section class="g-sec" id="الأنشطة">
  <h2><span class="num">٤</span> إنشاء الأنشطة ومسار اعتمادها</h2>
  <p class="lead">أهمّ ما يجب أن تفهمه: نشاطك لا يصل الطالب فور حفظه.</p>

  <h3>خيارات النشاط عند الإنشاء</h3>
  <div class="g-tablewrap">
    <table class="g-t">
      <thead><tr><th>الخيار</th><th>أثره المباشر</th></tr></thead>
      <tbody>
        <tr><td><strong>النقاط</strong></td><td>سقف ما يناله الطالب — ويأخذ منه بنسبة درجته</td></tr>
        <tr><td><strong>نوع السؤال</strong></td><td>يحدّد إن كان التصحيح آليّاً أم يدويّاً</td></tr>
        <tr><td><strong>الصعوبة</strong></td><td>تصنيفٌ للعرض والفرز</td></tr>
        <tr><td><strong>عدد المحاولات</strong></td><td>كم مرّة يُعيد الطالب — والنظام يمنحه الفرق فقط</td></tr>
        <tr><td><strong>مراجعة يدويّة</strong></td><td>يُجبِر مرور التسليم عليك حتّى لو كان قابلاً للتصحيح الآليّ</td></tr>
        <tr><td><strong>يتطلّب موافقة وليّ الأمر</strong></td><td>يوقف التسليم عند وليّ الأمر قبل أن يصلك</td></tr>
        <tr><td><strong>الفصل / الدرس</strong></td><td>ربط النشاط بفصلٍ بعينه أو بدرسٍ داخل قيمة</td></tr>
        <tr><td><strong>أنواع الملفّات المسموحة</strong></td><td>يحصر ما يرفعه الطالب (صورة/مستند/صوت/فيديو)</td></tr>
        <tr><td><strong>نشاط جماعيّ</strong></td><td>يُسنَد للفرق بدل الأفراد</td></tr>
      </tbody>
    </table>
  </div>

  <h3>مسار الاعتماد ذو المرحلتين</h3>
  <ol class="g-steps">
    <li><strong>تُنشئ النشاط</strong> فيُحفَظ بحالة <span class="g-tag maybe">بانتظار اعتماد المدرسة</span> — غير مرئيّ للطلاب.</li>
    <li><strong>مدير مدرستك يعتمده</strong> ← يصبح متاحاً <strong>لمدرستك أنت</strong> فوراً. وقد يرفضه بسبب، فتُصحّح وتُعيد الإرسال.</li>
    <li><strong>إدارة المنصّة قد تعتمده لاحقاً</strong> ← فيُنشَر لكلّ المدارس (أو لمدارس محدّدة) ويُنقَل إلى بنك الأنشطة المشترك ليستفيد منه كلّ المعلّمين.</li>
  </ol>

  <div class="g-note warn">
    <strong>انتبه: تعديل نشاطٍ معتمَد قد يعيده إلى الانتظار</strong>
    التعديل الجوهريّ يُعيد فتح دورة الاعتماد حمايةً من تغيير المحتوى بعد إجازته. عدّل قبل النشر ما استطعت، وإن اضطررت للتعديل بعده فتابع حالة النشاط ثمّ أعِد الإرسال.
  </div>

  <div class="g-note info">
    <strong>مفتاح الإجابات لا يصل الطالب أبداً</strong>
    ضع الإجابة الصحيحة بثقة: المنصّة تُنقّي مفاتيح الإجابات من كلّ ما يُرسَل لواجهة الطالب — في الويب وفي التطبيق معاً.
  </div>

  <h3>بنك الأنشطة — لا تبدأ من الصفر</h3>
  <p>البنك يضمّ أنشطةً معتمَدة ومتاحةً لمدرستك. أمامك طريقان:</p>
  <ul>
    <li><strong>نسخة قابلة للتعديل</strong>: تأخذ نسخةً تملكها وتعدّلها كما تشاء (وتدخل دورة الاعتماد من جديد).</li>
    <li><strong>إسناد مرجعيّ</strong>: تُسنِد النشاط الأصليّ لفصلك بلا نسخ — أسرع، لكن لا تعديل عليه.</li>
  </ul>
</section>

<section class="g-sec" id="المراجعة">
  <h2><span class="num">٥</span> طابور المراجعة والتصحيح</h2>
  <p class="lead">قلب عملك اليوميّ.</p>

  <h3>ما الذي يصلك؟</h3>
  <ul>
    <li>تسليمات <strong>بانتظار المراجعة</strong>: رفع ملفّ أو إجابة مقاليّة، أو نشاطٌ فعّلتَ فيه المراجعة اليدويّة.</li>
    <li>تسليمات <strong>تحتاج مراجعة</strong>: لم تجتَز درجة النجاح آليّاً، والقرار لك.</li>
  </ul>

  <div class="g-note info">
    <strong>لماذا لا أرى تسليماً أعلم أنّ الطالب أرسله؟</strong>
    إن كان النشاط يشترط موافقة وليّ الأمر ولم يوافق بعد، فالتسليم محجوبٌ عنك عمداً حتّى تُحسَم موافقته. وهذا مقصود لا خلل.
  </div>

  <h3>ما تملكه في كلّ تسليم</h3>
  <div class="g-tablewrap">
    <table class="g-t">
      <thead><tr><th>الإجراء</th><th>أثره</th></tr></thead>
      <tbody>
        <tr><td><strong>وضع درجة + ملاحظة</strong></td><td>يُعتمَد التسليم وتُمنَح نقاط الطالب وعملاته فوراً</td></tr>
        <tr><td><strong>الرفض مع سبب</strong></td><td>يعود للطالب ليُصحّح — واكتب السبب دائماً</td></tr>
        <tr><td><strong>السماح بإعادة المحاولة</strong></td><td>يفتح للطالب محاولةً إضافيّة استثناءً</td></tr>
        <tr><td><strong>تمييز التسليم</strong></td><td>يُبرزه كعملٍ متميّز ويظهر لدى إدارة المنصّة</td></tr>
      </tbody>
    </table>
  </div>

  <p>وترى في صفحة التسليم إجابة الطالب معروضةً بحسب نوعها: نصّاً، أو ترتيب صور، أو ملفّاً مرفوعاً مع ملاحظته، أو إجابات اختبارٍ كاملة مع المفتاح.</p>

  <div class="g-note warn">
    <strong>نطاق مراجعتك</strong>
    تراجع تسليمات طلاب فصولك، <em>وأيضاً</em> أيّ تسليم على نشاطٍ أنشأتَه أنت ولو كان الطالب خارج فصولك — شبكة أمان كي لا يبقى عمل طالبٍ بلا مُراجِع.
  </div>
</section>

