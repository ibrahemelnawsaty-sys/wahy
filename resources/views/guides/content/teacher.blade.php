<section class="g-sec" id="من-أنت">
  <h2><span class="num">١</span> من أنت داخل المنصّة</h2>
  <p class="lead">أنت <strong>المعلّم</strong> — صانع المحتوى وحَكَمُ التقدير. المنصّة تُؤتمِتُ الحساب والتذكير والتحفيز، لتتفرّغ أنت للتربية والحكم التربويّ.</p>

  <p>ثلاث مسؤوليّات تختصر دورك: <strong>تُنشئ</strong> أنشطةً وتمارين تُترجم القيمة إلى عمل، و<strong>تُصحّح</strong> ما لا تستطيع الآلة تصحيحه، و<strong>تتابع</strong> طلابك وأولياء أمورهم ببيانات لا بانطباعات.</p>

  <div class="g-grid">
    <div class="g-card"><span class="ico">📝</span><h5>تُنشئ</h5><p>أنشطة بأنواع أسئلة متعدّدة، وتمارين تدريبيّة، وفرق عمل.</p></div>
    <div class="g-card"><span class="ico">✅</span><h5>تُصحّح</h5><p>طابور مراجعة موحّد لكلّ ما يحتاج حكمك أنت.</p></div>
    <div class="g-card"><span class="ico">📊</span><h5>تتابع</h5><p>تقارير طالب وفصل، وتحليلات، ومقارنات قبليّة/بعديّة.</p></div>
    <div class="g-card"><span class="ico">🤝</span><h5>تتواصل</h5><p>مع طلابك وأولياء أمورهم وإدارة مدرستك.</p></div>
  </div>

  <div class="g-note info">
    <strong>أنت تكسب نقاطاً أيضاً</strong>
    لك رصيد نقاط ولوحة صدارة خاصّة بالمعلّمين. تفصيل ذلك في القسم السادس.
  </div>
</section>

