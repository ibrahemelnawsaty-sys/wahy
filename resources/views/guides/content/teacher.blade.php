<section class="g-sec" id="التمارين">
  <h2><span class="num">٨</span> التمارين والفِرق</h2>

  <h3>التمارين التدريبيّة 🏋️</h3>
  <p>تمارين خفيفة بأسئلتها الخاصّة، يحلّها الطالب فتُصحَّح آليّاً وتظهر نتيجته فوراً. يكسب منها <strong>الدرجة ÷ ١٠</strong> نقاط (١٠٠٪ ← ١٠ نقاط). وصفحة «النتائج» تُريك أداء كلّ طالب في كلّ تمرين — أداةُ تشخيصٍ ممتازة قبل الاختبارات.</p>

  <h3>الفِرق 👥</h3>
  <ol class="g-steps">
    <li><strong>أنشئ فريقاً</strong> وسمِّه.</li>
    <li><strong>وزّع الطلاب</strong> عليه.</li>
    <li><strong>أسنِد نشاطاً جماعيّاً</strong> للفريق.</li>
    <li><strong>قدّر عمل الفريق</strong> بدرجة واحدة.</li>
  </ol>
</section>

