    <p>راجع بالترتيب: هل اعتمده مدير المدرسة؟ هل النشاط نشِط؟ هل رُبِط بالفصل الصحيح؟ هل تاريخ الإتاحة بدأ؟ أكثر الأسباب شيوعاً هو الأوّل.</p>
