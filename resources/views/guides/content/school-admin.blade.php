<section class="g-sec" id="الاعتماد">
  <h2><span class="num">٥</span> اعتماد الأنشطة — دورك المحوريّ</h2>
  <p class="lead">لا يصل نشاطُ معلّمٍ إلى طالبٍ في مدرستك إلّا بمرورك أنت.</p>

  <ol class="g-steps">
    <li><strong>يُنشئ معلّمك نشاطاً</strong> فيدخل قائمة «اعتماد الأنشطة» عندك، غير مرئيّ لأحد.</li>
    <li><strong>تفتح صفحة النشاط</strong> وتفحص محتواه وأسئلته ونقاطه ومفتاح إجاباته.</li>
    <li><strong>تعتمده</strong> ← يصبح متاحاً لطلاب مدرستك فوراً بالوضع الذي تختاره. أو <strong>ترفضه بسبب</strong> ← يعود للمعلّم ليُصحّح ويُعيد الإرسال.</li>
  </ol>

  <div class="g-note info">
    <strong>ما بعد اعتمادك</strong>
    قد تعتمد إدارةُ المنصّة النشاط لاحقاً فتنشره لكلّ المدارس وتنقله لبنك الأنشطة المشترك. اعتمادك أنت يخصّ مدرستك، واعتمادهم يخصّ المنصّة كلّها — ولا يُلغي أحدهما الآخر.
  </div>

  <h4>معايير مقترحة للاعتماد</h4>
  <ul>
    <li>هل المحتوى سليمٌ لغويّاً وشرعيّاً وتربويّاً؟</li>
    <li>هل مفتاح الإجابة صحيح فعلاً؟ (خطأٌ فيه يظلم كلّ من يحلّه)</li>
    <li>هل النقاط متناسبة مع الجهد المطلوب؟</li>
    <li>هل نوع السؤال مناسب — ولماذا اختار المعلّم التصحيح اليدويّ إن اختاره؟</li>
    <li>هل ربط النشاط بالفصل والدرس الصحيحين؟</li>
  </ul>
</section>

