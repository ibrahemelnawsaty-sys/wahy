<section class="g-sec" id="التسجيل">
  <h2><span class="num">٤</span> بوّابة التسجيل: ثلاث طرق لبناء الحسابات</h2>

  <h3>١) الإدخال اليدويّ</h3>
  <p>الأدقّ للأعداد الصغيرة: تُنشئ الحساب بنفسك وتضبط بياناته وربطه مباشرة.</p>

  <h3>٢) الاستيراد الجماعيّ من Excel</h3>
  <ol class="g-steps">
    <li><strong>نزّل القالب</strong> من صفحة إدارة Excel — لا تصنع ملفّك من الصفر.</li>
    <li><strong>املأ البيانات</strong> بالأعمدة نفسها دون تغيير العناوين.</li>
    <li><strong>ارفع الملفّ</strong> وراجع تقرير الاستيراد: كم نجح وكم فشل ولماذا.</li>
    <li><strong>وزّع الحسابات</strong> على أصحابها.</li>
  </ol>
  <div class="g-note danger">
    <strong>كلمات المرور الأوّليّة</strong>
    الحسابات المستورَدة تُنشَأ بكلمة مرور أوّليّة، وكلّ مستخدمٍ سيُطالَب بتغييرها إلزاميّاً عند أوّل دخول. لا تنشر هذه الكلمات في مجموعةٍ عامّة، وسلّم كلّ حسابٍ لصاحبه.
  </div>

  <h3>٣) التسجيل الذاتيّ برابط أو رمز QR</h3>
  <p>لكلّ دور (معلّم/طالب/وليّ أمر) رابطٌ ورمز QR خاصّ بمدرستك. انشره في مجموعة أو مطبوعة، فيسجّل المستخدم بنفسه ويصلك طلبه في «طلبات التسجيل» لتقبله أو ترفضه.</p>

  <div class="g-tablewrap">
    <table class="g-t">
      <thead><tr><th>الأداة</th><th>متى تستخدمها</th></tr></thead>
      <tbody>
        <tr><td><strong>تجديد الرمز</strong></td><td>إذا تسرّب الرابط خارج مدرستك — يُبطِل القديم فوراً</td></tr>
        <tr><td><strong>إيقاف التسجيل</strong></td><td>بعد اكتمال التسجيل، لإغلاق الباب نهائيّاً</td></tr>
      </tbody>
    </table>
  </div>

  <div class="g-note warn">
