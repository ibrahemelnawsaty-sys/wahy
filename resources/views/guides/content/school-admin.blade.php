<section class="g-sec" id="من-أنت">
  <h2><span class="num">١</span> من أنت داخل المنصّة</h2>
  <p class="lead">أنت <strong>مدير المدرسة</strong> — صاحب السلطة الكاملة داخل حدود مدرستك، ولا شيء خارجها. أنت من يفتح الأبواب، ويعتمد المحتوى، ويحسم ما تعطّل.</p>

  <p>أربع مسؤوليّات تختصر دورك: <strong>تبني المدرسة</strong> (معلّمون، طلاب، أولياء أمور، فصول)، و<strong>تحرس البوّابة</strong> (طلبات التسجيل واعتماد الأنشطة)، و<strong>تحسم العالِق</strong> حين يتأخّر معلّمٌ أو وليّ أمر، و<strong>تقرأ الأرقام</strong> لتقود قرارك.</p>

  <div class="g-grid">
    <div class="g-card"><span class="ico">🏗️</span><h5>تبني</h5><p>حسابات ثلاثة أدوار وفصول دراسيّة، فرديّاً أو بالجملة عبر Excel.</p></div>
    <div class="g-card"><span class="ico">🚪</span><h5>تحرس</h5><p>طلبات التسجيل واعتماد أنشطة معلّميك قبل وصولها للطلاب.</p></div>
    <div class="g-card"><span class="ico">⚖️</span><h5>تحسم</h5><p>التسليمات العالقة التي لم يتجاوب معها معلّم أو وليّ أمر.</p></div>
    <div class="g-card"><span class="ico">📊</span><h5>تقيس</h5><p>إحصاءات المدرسة وترتيبها وتفاعل أولياء الأمور وأثر القيم.</p></div>
  </div>

  <div class="g-note info">
    <strong>حدودك واضحة ومقصودة</strong>
    كلّ ما تراه وتفعله مقصورٌ على مدرستك: لا ترى طلاب مدرسةٍ أخرى، ولا تُعدّل إعدادات المنصّة العامّة، ولا تُنشئ القيم والدروس. هذا عزلٌ مُصمَّم لا نقصٌ في الصلاحيّة.
  </div>
</section>

<section class="g-sec" id="البداية">
  <h2><span class="num">٢</span> تجهيز مدرستك من الصفر</h2>
  <p class="lead">الترتيب هنا مهمّ: كلّ خطوة تعتمد على ما قبلها.</p>

  <ol class="g-steps">
    <li><strong>أنشئ الفصول أوّلاً.</strong> الفصل هو الوعاء الذي يربط المعلّم بالطلاب — وبدونه لا يصل نشاطٌ ولا تُحسَب متابعة.</li>
    <li><strong>أضِف المعلّمين</strong> واربط كلّ معلّم بفصوله.</li>
    <li><strong>أضِف الطلاب</strong> ووزّعهم على الفصول. للأعداد الكبيرة استخدم الاستيراد من Excel.</li>
    <li><strong>أضِف أولياء الأمور</strong> واربط كلّ وليّ بأبنائه — هذه الخطوة تُنسى كثيراً فتتعطّل المتابعة الأسريّة كلّها.</li>
    <li><strong>فعّل روابط التسجيل الذاتيّ</strong> إن أردت أن يسجّل المستخدمون أنفسهم بدل إدخالهم يدويّاً.</li>
    <li><strong>اضبط إعدادات المدرسة</strong> ثمّ راجع الإحصاءات بعد أوّل أسبوع.</li>
  </ol>

  <div class="g-note warn">
    <strong>الخطأ الأكثر تكراراً</strong>
    إنشاء الطلاب قبل الفصول، أو إغفال ربط وليّ الأمر بأبنائه. الأوّل يُنتج طلاباً بلا معلّم يراهم، والثاني يُنتج أولياء أمورٍ يرون لوحةً فارغة.
  </div>
</section>

