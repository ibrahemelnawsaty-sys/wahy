  <details class="g-faq"><summary>معلّم يقول إنّ نشاطه لا يظهر لطلابه</summary><div class="body">
    <p>افتح «اعتماد الأنشطة» — الأرجح أنّه ينتظرك. وإن كنتَ اعتمدتَه فتحقّق من ربطه بالفصل الصحيح ومن كونه نشِطاً.</p>
  </div></details>

  <details class="g-faq"><summary>وليّ أمر يقول إنّه لا يرى ابنه</summary><div class="body">
    <p>الربط بين وليّ الأمر وأبنائه لا يتمّ تلقائيّاً. افتح ملفّ وليّ الأمر واربطه بأبنائه صراحةً.</p>
  </div></details>

  <details class="g-faq"><summary>طالب لا يظهر لمعلّمه</summary><div class="body">
    <p>الطالب غير مُسنَدٍ لفصلٍ يدرّسه ذلك المعلّم. راجع الفصل وتوزيع الطلاب وإسناد المعلّم.</p>
  </div></details>

  <details class="g-faq"><summary>تسجيلات لا أعرف أصحابها تصلني</summary><div class="body">
    <p>رابط التسجيل انتشر خارج نطاقك. ارفض الطلبات غير المعروفة، ثمّ جدّد الرمز فوراً ليبطل القديم، وأوقِف التسجيل عند اكتماله.</p>
  </div></details>

  <details class="g-faq"><summary>أريد حذف فصل أو معلّم</summary><div class="body">
    <p>الحذف إجراءٌ واسع الأثر: راجع أوّلاً ما يرتبط به من طلاب وأنشطة وتسليمات. الأفضل غالباً تعطيل الحساب أو نقل الطلاب بدل الحذف النهائيّ.</p>
  </div></details>
