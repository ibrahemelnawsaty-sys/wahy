  <p>دورك ليس مشاهدةً سلبيّة: أنت <strong>ترى</strong> تقدّم أبنائك بالأرقام، و<strong>تُحفّز</strong> بالتشجيع والهدايا، و<strong>تُصادِق</strong> على أنشطةٍ تحتاج شهادتك، و<strong>تتواصل</strong> مع معلّميهم مباشرة.</p>

  <div class="g-grid">
    <div class="g-card"><span class="ico">👀</span><h5>ترى</h5><p>نقاط أبنائك ومستوياتهم وأنشطتهم وتقدّمهم لحظةً بلحظة.</p></div>
    <div class="g-card"><span class="ico">💝</span><h5>تُحفّز</h5><p>رسائل تشجيع وهدايا تُضيف نقاطاً حقيقيّة لرصيد ابنك.</p></div>
