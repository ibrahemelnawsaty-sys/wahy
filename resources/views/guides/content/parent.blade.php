  <p>اكتب رسالةً واختر نوعها: تشجيع عامّ، أو إشادة بإنجاز، أو ثناء على سلوك، أو رسالة خاصّة تصوغها بنفسك. تصل ابنك في صفحة «هداياي» وفي إشعاراته.</p>

