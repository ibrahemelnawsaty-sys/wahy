  <h2><span class="num">٧</span> آداب مهنة الدعم</h2>
  <ol>
    <li><strong>أقرّ بالاستلام سريعاً</strong> ولو لم يكن الحلّ جاهزاً. الصمت أسوأ من التأخير.</li>
    <li><strong>اسأل سؤالاً واحداً واضحاً</strong> في كلّ ردّ، لا خمسة أسئلة تُربك المستخدم.</li>
