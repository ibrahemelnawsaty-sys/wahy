  <p>دورك مصمَّم بعنايةٍ ليكون <strong>واسع الوصول ضيّق الصلاحيّة</strong>: تخدم مستخدمي كلّ المدارس بلا حدود جغرافيّة، لكنّ ما تستطيع تغييره محصورٌ عمداً في أضيق نطاقٍ يكفي لحلّ المشكلة.</p>

  <div class="g-grid">
