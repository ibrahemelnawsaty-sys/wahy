<section class="g-sec" id="أدلة">
  <h2><span class="num">٥</span> أدلّة معالجة أكثر البلاغات تكراراً</h2>

  <details class="g-faq"><summary>«لا أستطيع تسجيل الدخول»</summary><div class="body">
    <p><strong>١)</strong> تحقّق من صحّة البريد المكتوب. <strong>٢)</strong> افحص حالة الحساب — قد يكون معطّلاً. <strong>٣)</strong> إن كان تسجيلاً ذاتيّاً فقد يكون الطلب ما زال معلّقاً لدى مدير المدرسة، وهنا حوّله إليه. <strong>٤)</strong> وإلّا فأعِد تعيين كلمة المرور وسلّمها لصاحب الحساب عبر قناة موثوقة.</p>
  </div></details>

  <details class="g-faq"><summary>«نقاطي لم تصل»</summary><div class="body">
    <p>هذا سؤال تشغيليّ لا تقنيّ في الغالب. اسأل: هل النشاط بتصحيح يدويّ؟ إذاً ينتظر المعلّم. هل يشترط موافقة وليّ الأمر؟ إذاً ينتظره. هل هي إعادة محاولة؟ فالنظام يمنح الفرق فوق أفضل نتيجة فقط. وجّه المستخدم لمعلّمه أو مدير مدرسته، ولا تَعِد بتعديل النقاط فأنت لا تملكه.</p>
  </div></details>

  <details class="g-faq"><summary>«لا أستطيع رفع ملفّ»</summary><div class="body">
    <p>اطلب: امتداد الملفّ، وحجمه بالميغابايت، ونصّ رسالة الخطأ، واسم النشاط. أكثر الأسباب أنّ النوع غير مسموحٍ في ذلك النشاط تحديداً. إن كان الملفّ ضمن المسموح وما زال يفشل، فصعّد التذكرة مرفقةً بهذه التفاصيل.</p>
  </div></details>

  <details class="g-faq"><summary>«ابني لا يظهر في حسابي» (وليّ أمر)</summary><div class="body">
    <p>الربط بين وليّ الأمر وأبنائه من صلاحيّة مدير المدرسة وحده. حوّل التذكرة إليه — ولا تحاول تعديل البيانات لأنّ نقل المستخدمين وربطهم خارج صلاحيّتك.</p>
  </div></details>

  <details class="g-faq"><summary>«الصفحة لا تفتح أو تُظهر خطأ»</summary><div class="body">
    <p>اجمع: الرابط الكامل، ووقت الحدوث، والمتصفّح والجهاز، ولقطة شاشة، وهل تتكرّر مع مستخدمين آخرين. ثمّ صعّدها بأولويّةٍ عالية إن كانت تمنع العمل.</p>
  </div></details>

  <details class="g-faq"><summary>«لا تصلني رسائل البريد»</summary><div class="body">
    <p>اطلب التحقّق من مجلّد الرسائل غير المرغوبة أوّلاً، ومن صحّة البريد المسجّل. إن تأكّد أنّ المشكلة من المنصّة فصعّدها — سجلّ البريد الصادر متاحٌ لإدارة المنصّة وحدها.</p>
  </div></details>
</section>

<section class="g-sec" id="التصعيد">
  <h2><span class="num">٦</span> متى تُصعّد؟</h2>

  <p><strong>صعّد فوراً</strong> إذا كانت التذكرة:</p>
  <ul>
    <li>تتعلّق بحساب مدير مدرسة أو مدير نظام أو زميلٍ في الدعم.</li>
    <li>تطلب تغيير دور أو نقل مستخدمٍ بين المدارس.</li>
    <li>تتعلّق بخطأ في محتوى تعليميّ أو مفتاح إجابة.</li>
    <li>تخصّ النقاط أو الدرجات أو الاقتصاد.</li>
    <li>تكشف ثغرةً أمنيّة أو تسريب بيانات — <strong>وهذه أعلى أولويّة على الإطلاق</strong>.</li>
    <li>تمسّ عدداً كبيراً من المستخدمين في وقتٍ واحد.</li>
  </ul>

  <div class="g-note danger">
    <strong>بلاغات الأمان لا تُناقَش في التذكرة</strong>
    إن أبلغ مستخدمٌ عن رؤيته بيانات غيره أو وصوله لما لا يخصّه، فصعّدها فوراً بأعلى أولويّة، ولا تطلب منه إعادة المحاولة «للتأكّد» — فذلك يوسّع أثر المشكلة ويُعرّض بيانات أكثر.
  </div>

  <h3>ما يجب أن تحتويه التذكرة المُصعَّدة</h3>
  <ul>
    <li>وصفٌ دقيق للمشكلة كما وقعت، لا كما فُسِّرت.</li>
    <li>خطوات إعادة إنتاجها بالترتيب.</li>
    <li>الحساب المتأثّر والمدرسة والوقت.</li>
    <li>ما جرّبتَه أنت ونتيجته.</li>
    <li>مدى الأثر: مستخدمٌ واحد أم فصل أم مدرسة كاملة؟</li>
  </ul>
</section>

