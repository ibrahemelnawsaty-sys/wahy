    <li><strong>تحقّق قبل أن تُغلق.</strong> «حُلّت» تعني أنّك تأكّدت، لا أنّك أرسلت اقتراحاً.</li>
    <li><strong>احترم الخصوصيّة.</strong> لا تشارك بيانات مستخدمٍ مع آخر، ولو كان معلّمه أو والده، إلّا عبر القنوات النظاميّة.</li>
    <li><strong>وثّق كلّ إجراء داخل التذكرة</strong> لا في قنوات جانبيّة — فمن يخلفك سيقرأ التذكرة وحدها.</li>
  </ol>
