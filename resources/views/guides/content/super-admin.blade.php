<section class="g-sec" id="روتين">
  <h2><span class="num">١٠</span> روتين تشغيليّ مقترح</h2>

  <h3>يوميّاً</h3>
  <ul>
    <li>راجع اعتماد الأنشطة ورسائل «تواصل معنا».</li>
    <li>تفقّد سجلّ البريد الصادر بحثاً عن إخفاقات.</li>
  </ul>

  <h3>أسبوعيّاً</h3>
  <ul>
    <li>أنشئ نسخةً احتياطيّة ونزّلها خارج الخادم.</li>
    <li>راجع التقارير: مدارس متأخّرة، أنشطة لا يُنجزها أحد.</li>
    <li>تصفّح سجلّ الأنشطة بحثاً عن إجراءات غير متوقّعة.</li>
  </ul>

  <h3>شهريّاً</h3>
  <ul>
    <li>راجع توازن الاقتصاد: أسعار المتجر ونقاط الأنشطة وشروط الشارات.</li>
    <li>نظّف النسخ الاحتياطيّة القديمة والحسابات المهجورة.</li>
    <li>اقرأ تقارير مقارنة الاستبيانات — فهي مقياس الأثر الحقيقيّ للمنصّة.</li>
  </ul>
</section>
