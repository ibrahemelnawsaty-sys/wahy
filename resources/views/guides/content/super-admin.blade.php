<section class="g-sec" id="النظام">
  <h2><span class="num">٨</span> النظام والسلامة</h2>

  <h3>النسخ الاحتياطيّ</h3>
  <ul>
    <li><strong>أنشئ نسخةً</strong> قبل كلّ تغييرٍ واسع: استيراد ضخم، تعديل بنيويّ، أو حذفٍ جماعيّ.</li>
    <li><strong>نزّل النسخ المهمّة</strong> واحفظها خارج الخادم — نسخةٌ على الخادم نفسه ليست نسخةً احتياطيّة حقيقيّة.</li>
    <li><strong>نظّف القديم</strong> دوريّاً لئلّا تمتلئ المساحة.</li>
  </ul>

  <div class="g-note danger">
    <strong>الاسترجاع يستبدل البيانات الحاليّة</strong>
    استرجاع نسخةٍ يُلغي كلّ ما استُجدّ بعد تاريخها. خُذ نسخةً من الوضع الحاليّ قبل الاسترجاع، ولا تسترجع إلّا بعد تحديد ما ستفقده بالضبط.
  </div>

  <h3>سجلّ الأنشطة</h3>
  <p>يسجّل من فعل ماذا ومتى. ابدأ منه في كلّ تحقيق: «من غيّر هذا الإعداد؟»، «من حذف هذا الحساب؟».</p>

  <h3>حسابات المستخدمين</h3>
  <ul>
    <li><strong>التعطيل أأمن من الحذف</strong>: يقطع الوصول ويحفظ البيانات والتاريخ.</li>
    <li><strong>الأدوار الثانويّة</strong>: يمكن أن يحمل المستخدم أكثر من دور ويبدّل بينها (كمعلّمٍ هو وليّ أمرٍ أيضاً).</li>
    <li><strong>التحقّق بخطوتين</strong> يُفعَّل من صفحة المستخدم — فعّله لحسابات الإدارة أوّلاً.</li>
  </ul>

  <div class="g-note warn">
    <strong>احتفظ بأكثر من حساب مدير نظام</strong>
    فقدان الحساب الوحيد ذي الصلاحيّة الكاملة مشكلةٌ تشغيليّة خطيرة. أبقِ حساباً احتياطيّاً موثوقاً.
  </div>
</section>

