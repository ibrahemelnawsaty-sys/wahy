<section class="g-sec" id="التسلسل">
  <h2><span class="num">٣</span> تسلسل بناء المحتوى</h2>
  <p class="lead">لا تبدأ من الأنشطة. المنصّة مبنيّة على تسلسلٍ صارم:</p>

  <div class="g-formula">
    <div class="eq">القيمة ← المفهوم ← الدرس ← النشاط ← تسليم الطالب</div>
    <div class="hint">كلّ طبقةٍ تحتاج ما قبلها ليكون لها معنى</div>
  </div>

  <ol class="g-steps">
    <li><strong>أنشئ القيمة</strong> (الصدق، الأمانة، برّ الوالدين…) — وهي الجذر.</li>
    <li><strong>فعّل القيمة للمدارس المناسبة.</strong> لكلّ مدرسة قائمة «قيم نشِطة» خاصّة، فليس كلّ قيمةٍ تصلح لكلّ مدرسة أو مرحلة.</li>
    <li><strong>أضِف المفاهيم والدروس</strong> تحت القيمة، واضبط سلسلة الالتزام في الدرس إن أردت توزيع أنشطته على أيّام.</li>
    <li><strong>أنشئ الأنشطة</strong> واربطها بالدرس، وحدّد نقاطها ونوعها ومحاولاتها.</li>
    <li><strong>أضِف استبياناً قبليّاً/بعديّاً</strong> للقيمة إن أردت قياس أثرها.</li>
  </ol>

  <div class="g-note warn">
    <strong>قيمةٌ غير مفعّلة لمدرسة = محتوى غير مرئيّ</strong>
    أكثر شكوى «المحتوى لا يظهر» سببها أنّ القيمة لم تُفعَّل لتلك المدرسة. افحص هذا أوّلاً قبل أيّ تشخيصٍ آخر.
  </div>
</section>

<section class="g-sec" id="الاعتماد">
  <h2><span class="num">٤</span> اعتماد الأنشطة ونشرها</h2>
  <p class="lead">أنت المرحلة الثانية والأخيرة في سلسلة الاعتماد.</p>

  <div class="g-tablewrap">
    <table class="g-t">
      <thead><tr><th>المرحلة</th><th>من يقوم بها</th><th>الأثر</th></tr></thead>
      <tbody>
        <tr><td>الإنشاء</td><td>المعلّم</td><td>غير مرئيّ لأحد</td></tr>
        <tr><td>الاعتماد الأوّل</td><td>مدير المدرسة</td><td>متاح لمدرسته وحدها</td></tr>
        <tr><td><strong>الاعتماد الثاني</strong></td><td><strong>أنت</strong></td><td>نشرٌ لكلّ المدارس أو لمدارس محدّدة + نقلٌ لبنك الأنشطة</td></tr>
      </tbody>
    </table>
  </div>

  <h3>خيارا النشر</h3>
  <ul>
    <li><strong>كلّ المدارس</strong>: النشاط متاحٌ للمنصّة بأسرها.</li>
    <li><strong>مدارس محدّدة</strong>: تختار المدارس بعينها — وانتبه أنّ هذا الاختيار <em>يحصر</em> النطاق حصراً، فالمدارس المُزالة من الاختيار تفقد النشاط ولو كانت اعتمدته سابقاً.</li>
  </ul>

  <div class="g-note info">
    <strong>الاعتماد ينقل النشاط تلقائيّاً إلى بنك الأنشطة</strong>
    فيصبح متاحاً لكلّ المعلّمين لنسخه أو إسناده. هذه أقوى وسيلةٍ لديك لتعميم المحتوى الجيّد.
  </div>

  <div class="g-note danger">
    <strong>الرفض يسحب النشر بالكامل</strong>
    رفضك يُزيل النشاط من كلّ المدارس والفصول فوراً — بما فيها نشرُ مدير المدرسة في المرحلة الأولى. تأكّد قبل الرفض، فالطلاب سيفقدون النشاط في اللحظة نفسها.
  </div>
</section>

<section class="g-sec" id="الاقتصاد">
  <h2><span class="num">٥</span> ضبط الاقتصاد والتحفيز</h2>
  <p class="lead">أنت من يضبط توازن المنصّة كلّها. هذه القواعد الثابتة التي تبني عليها.</p>

  <h3>القواعد الثابتة في المنصّة</h3>
  <div class="g-tablewrap">
    <table class="g-t">
      <thead><tr><th>القاعدة</th><th>القيمة</th></tr></thead>
      <tbody>
