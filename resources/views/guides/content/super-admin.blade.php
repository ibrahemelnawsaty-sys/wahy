      </tbody>
    </table>
  </div>

  <h3>ما تتحكّم فيه أنت</h3>
  <ul>
    <li><strong>نقاط كلّ نشاط ودرس</strong> — أقوى مقبضٍ بيدك لضبط التوازن.</li>
    <li><strong>أسعار المتجر وأنواع عناصره</strong>: تجميليّ (يُجهَّز فقط)، قوّة أو خاصّ (يُستخدَم مرّةً ويمنح أثراً).</li>
    <li><strong>شروط الشارات</strong> من ستّة مقاييس: الأنشطة المكتملة، المستوى، السلسلة، النقاط، الدروس المكتملة، القيم المُتقَنة.</li>
    <li><strong>تحدّيات PvP</strong>: إنشاؤها وتفعيلها وإيقافها.</li>
    <li><strong>نقاط موافقة وليّ الأمر</strong> ضمن الإعدادات العامّة.</li>
  </ul>

  <div class="g-note danger">
    <strong>احذر عناصر المتجر التي تمنح نقاطاً</strong>
    عنصرٌ ثمنه ٥٠ عملة ويمنح ١٠٠ نقطة يفتح دورةً تُسكّ فيها النقاط من العدم وتُفسِد لوحة الصدارة. اجعل أثر العنصر أقلّ ممّا يمكن كسبه بالعمل، واقصر الآثار على نوعَي «قوّة» و«خاصّ» فقط.
  </div>

  <div class="g-note info">
    <strong>لا مضاعفة ممكنة</strong>
    كلّ منحةٍ في المنصّة مقيَّدة بمفتاحٍ فريد لحدثها: إعادة الإرسال أو التحديث أو الضغط المزدوج لا تمنح شيئاً مرّتين. وإعادة المحاولة تمنح الفرق التصاعديّ فوق أفضل نتيجة فقط.
  </div>
</section>

