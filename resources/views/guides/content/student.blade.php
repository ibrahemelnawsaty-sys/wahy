<section class="g-sec" id="من-أنت">
  <h2><span class="num">١</span> من أنت داخل المنصّة</h2>
  <p class="lead">أنت <strong>الطالب</strong> — محور المنصّة كلّها. كلّ ما يبنيه المعلّم والمدرسة والأدمن غايته شاشةٌ واحدة: شاشتك.</p>

  <p>المنصّة ليست بنكَ واجبات، بل <strong>رحلة قِيَم</strong>: تتعلّم قيمة (كالصدق أو الأمانة)، تُنجز أنشطتها، فتكسب نقاط خبرة وعملات وشارات وتاجاً للقيمة حين تُتقنها. تقدّمك يُرى فوراً عند معلّمك ووليّ أمرك ومدرستك.</p>

  <div class="g-grid">
    <div class="g-card"><span class="ico">🎯</span><h5>تتعلّم</h5><p>دروس ومحتوى مرئيّ ونصّيّ منظّم داخل كلّ قيمة.</p></div>
    <div class="g-card"><span class="ico">✍️</span><h5>تُنجز</h5><p>أنشطة وتمارين وتحدّيات فرديّة وجماعيّة.</p></div>
    <div class="g-card"><span class="ico">⭐</span><h5>تكسب</h5><p>نقاط خبرة، عملات، مستويات، شارات، تيجان.</p></div>
    <div class="g-card"><span class="ico">🛒</span><h5>تصرف</h5><p>تشتري من المتجر بعملاتك وتُجهّز مقتنياتك.</p></div>
  </div>

  <div class="g-note info">
    <strong>فرقٌ مهمّ منذ البداية: النقاط ≠ العملات</strong>
    <strong style="display:inline">النقاط (XP)</strong> تقيس تقدّمك وترفع مستواك وترتيبك في لوحة الصدارة — ولا تُنفَق أبداً ولا تنقص.
    أمّا <strong style="display:inline">العملات 🪙</strong> فهي عُملة الشراء: تُكتسَب وتُنفَق في المتجر. شراؤك من المتجر لا يُنقص نقاطك ولا يُنزل مستواك.
  </div>
</section>

<section class="g-sec" id="البداية">
  <h2><span class="num">٢</span> أوّل خمس دقائق</h2>
  <p class="lead">من استلام الحساب حتّى أوّل نشاط مُنجَز.</p>

  <ol class="g-steps">
    <li><strong>احصل على حسابك</strong> بإحدى ثلاث طرق: تُنشئه مدرستك مباشرة، أو تُضاف ضمن ملفّ Excel جماعيّ، أو تُسجّل بنفسك عبر رابط/رمز QR تنشره مدرستك — وفي الحالة الأخيرة يبقى طلبك <span class="g-tag maybe">بانتظار الموافقة</span> حتّى يعتمده مدير المدرسة.</li>
    <li><strong>سجّل الدخول</strong> من صفحة الدخول بالبريد وكلمة المرور.</li>
    <li><strong>غيّر كلمة المرور المؤقّتة.</strong> إن كان حسابك مُنشأً من المدرسة أو من الدعم الفنّيّ، ستُطالَب بتغيير الكلمة قبل أيّ شيء آخر — وهذا إجباريّ ولا يمكن تخطّيه.</li>
    <li><strong>أكمل ملفّك الشخصيّ</strong>: صورة رمزيّة واسم ظاهر من صفحة «ملفّي».</li>
    <li><strong>افتح «رحلتي»</strong> واختر أوّل قيمة، ثمّ أوّل درس، ثمّ أوّل نشاط — وستأتيك أوّل نقاطك فور التسليم.</li>
  </ol>

  <div class="g-note warn">
    <strong>قد يظهر لك استبيان قبل أن تبدأ</strong>
    بعض المدارس تُفعّل «تقييماً قبليّاً» للقيمة: نافذة استبيان تظهر لك قبل بدء القيمة أو الدرس، وأخرى «بعديّة» عند إتمامها. هذه الاستبيانات إلزاميّة أحياناً ولن تُغلق حتّى تُجيب، والهدف منها قياس أثر القيمة فيك قبل وبعد — لا تقييمك أنت.
  </div>
