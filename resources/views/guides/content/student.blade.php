<section class="g-sec" id="المتجر">
  <h2><span class="num">٨</span> المتجر والمقتنيات</h2>
  <p class="lead">هنا تُنفَق العملات — والعملات وحدها.</p>

  <ol class="g-steps">
    <li><strong>تصفّح المتجر</strong> واختر عنصراً ضمن رصيدك.</li>
    <li><strong>اشترِ</strong> — يُخصم الثمن فوراً ويُسجَّل في سجلّ العملات.</li>
    <li><strong>افتح «مقتنياتي»</strong>: العناصر التجميليّة (أڤاتار، ثيم، إطار) <em>تُجهَّز</em> فتظهر في ملفّك، والقوى والعناصر الخاصّة <em>تُستخدَم</em>.</li>
  </ol>

  <div class="g-note warn">
    <strong>القوى تُستخدَم مرّةً واحدة</strong>
    استخدام «قوّة» يمنحك نقاطاً أو عملات بحسب نوعها (وبعضها مفاجأة بمقدار عشوائيّ ضمن مدى)، ثمّ يُختَم العنصر كمُستخدَم فلا يُعاد استخدامه. أمّا العناصر التجميليّة فلا تُستخدَم ولا تمنح نقاطاً — تُجهَّز فقط.
  </div>

  <p>راجع <strong>سجلّ العملات</strong> متى شككتَ في رصيدك: كلّ سطر يحمل السبب والتاريخ، دخلاً كان أم صرفاً.</p>
</section>

<section class="g-sec" id="الأنشطة">
