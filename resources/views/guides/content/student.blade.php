  <p class="lead">لماذا تظهر أنشطتك أحياناً «بانتظار المراجعة» بلا نقاط؟ هذا التفصيل الكامل.</p>

  <h3>أنواع الأسئلة التي قد تواجهها</h3>
  <ul>
    <li><strong>اختيار من متعدّد</strong> و<strong>صح/خطأ</strong> و<strong>اختيار بالحروف</strong> — تصحيح آليّ فوريّ.</li>
    <li><strong>إجابة قصيرة</strong> — تصحيح آليّ بمطابقة نصّيّة مرنة.</li>
    <li><strong>ترتيب عناصر</strong> و<strong>ترتيب صور</strong> — تصحيح آليّ بمقارنة الترتيب.</li>
    <li><strong>اختبار متعدّد الأسئلة</strong> — درجتك نسبة الصحيح من المجموع.</li>
    <li><strong>رفع ملفّ</strong> أو <strong>إجابة مقاليّة</strong> — تصحيح يدويّ من معلّمك.</li>
