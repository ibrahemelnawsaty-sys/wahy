  <h2><span class="num">٤</span> كيف تكسب النقاط — القواعد الدقيقة</h2>
  <p class="lead">هذا أهمّ قسم في دليلك. كلّ رقمٍ هنا مأخوذ من قواعد المنصّة الفعليّة، لا تقديراً.</p>

  <h3>أوّلاً: نقاط النشاط — المعادلة</h3>
  <p>لكلّ نشاط «قيمة نقاط» يحدّدها مُنشئه. ما تناله ليس النقاط كاملةً، بل بنسبة درجتك:</p>

