    <div class="hint">وإن كسبتَ نقطةً واحدة على الأقلّ، فلن تقلّ عملاتك عن عملة واحدة</div>
  </div>

  <h3>ثالثاً: إعادة المحاولة — قاعدة «أفضل محاولة»</h3>
  <p>إن سمح النشاط بأكثر من محاولة، فالنظام يحتفظ بأفضل نتيجةٍ لك ويمنحك <strong>الفرق فقط</strong>:</p>
  <ul>
    <li>محاولة أولى ٦٠٪ على نشاط من ٥٠ ← تنال ٣٠ نقطة.</li>
    <li>محاولة ثانية ٩٠٪ ← لا تنال ٤٥ جديدة، بل <strong>١٥ فقط</strong> (الفرق) ليصير مجموعك ٤٥.</li>
    <li>محاولة ثالثة ٧٠٪ ← <strong>لا شيء يُخصَم ولا يُضاف</strong>؛ يبقى رصيدك عند أفضل نتيجة (٩٠٪).</li>
  </ul>
  <div class="g-note ok">
    <strong>الخلاصة: الإعادة لا تضرّك أبداً</strong>
    لا يمكن أن تخسر نقاطاً بإعادة المحاولة، ولا يمكن أن تُضاعف نقاطك بإعادة نشاطٍ نجحتَ فيه. حاوِل بلا خوف.
