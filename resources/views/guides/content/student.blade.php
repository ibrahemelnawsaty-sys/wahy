<section class="g-sec" id="مشاكل">
  <h2><span class="num">١٢</span> حلّ المشكلات الشائعة</h2>

  <details class="g-faq"><summary>سلّمتُ النشاط ولم تصلني أيّ نقاط</summary><div class="body">
    <p>ثلاثة أسباب محتملة، بالترتيب: <strong>(١)</strong> النشاط بتصحيح يدويّ فالنقاط تنتظر معلّمك. <strong>(٢)</strong> النشاط يشترط موافقة وليّ أمرك ولم يوافق بعد. <strong>(٣)</strong> إعادةٌ لمحاولة سابقة أفضل، فلا فرق يُمنَح. افتح صفحة النشاط وانظر حالة تسليمك.</p>
  </div></details>

  <details class="g-faq"><summary>نقاطي زادت لكنّ عملاتي لم تتغيّر</summary><div class="body">
    <p>مصادر مثل مكافأة الالتزام وتشجيع وليّ الأمر تمنح نقاطاً بلا عملات. العملات تأتي أساساً من الأنشطة وترقية المستوى ومعالِم السلاسل والفوز بالتحدّي.</p>
  </div></details>

  <details class="g-faq"><summary>سلسلتي عادت إلى صفر</summary><div class="body">
    <p>غبتَ يوماً تقويميّاً كاملاً. السلسلة تُقاس بالأيّام لا بالساعات، ولا تُستعاد بأثرٍ رجعيّ. أطول سلسلةٍ بلغتَها تبقى محفوظةً في سجلّك.</p>
  </div></details>

  <details class="g-faq"><summary>نشاطٌ اختفى من قائمتي</summary><div class="body">
    <p>غالباً أُوقِف أو سُحِب اعتماده أو غُيّر نطاق نشره. الأنشطة تظهر لك فقط إن كانت نشِطة ومعتمَدة ومنشورةً لمدرستك أو فصلك. راجع معلّمك.</p>
  </div></details>

  <details class="g-faq"><summary>لا أستطيع رفع ملفّ الإجابة</summary><div class="body">
    <p>تحقّق من نوع الملفّ أوّلاً (كلّ نشاط يحدّد أنواعه المسموحة)، ثمّ من حجمه. إن استمرّت المشكلة فافتح تذكرة دعم واذكر اسم النشاط ونوع الملفّ وحجمه.</p>
  </div></details>

  <details class="g-faq"><summary>ترتيبي في لوحة الصدارة لا يتحرّك</summary><div class="body">
    <p>اللوحة مقصورة على طلاب مدرستك وتُرتَّب بمجموع النقاط. زملاؤك يكسبون أيضاً، فثبات ترتيبك مع زيادة نقاطك أمرٌ طبيعيّ.</p>
  </div></details>

  <details class="g-faq"><summary>نسيتُ كلمة المرور</summary><div class="body">
    <p>استخدم «نسيت كلمة المرور» في صفحة الدخول. وإن تعذّر، فمدير مدرستك أو الدعم الفنّيّ يستطيع إعادة تعيينها — وستُطالَب بتغييرها فور دخولك.</p>
  </div></details>
