  </div>

  <div class="g-note warn">
    <strong>رفع الملفّات</strong>
    كلّ نشاطٍ يحدّد الأنواع المسموحة (صورة/مستند/صوت/فيديو) وحجماً أقصى. إن رُفِض ملفّك فراجع النوع أوّلاً، ثمّ الحجم — والمنصّة تُظهر لك سبب الرفض صراحةً بدل أن تفشل بصمت.
  </div>
