    <li><strong>إن كان يدويّاً</strong>، يصل معلّمك إشعارٌ وينتقل تسليمك إلى طابور مراجعته.</li>
    <li><strong>يُصحّح معلّمك</strong> ويضع الدرجة والملاحظة — فتُمنَح نقاطك وعملاتك عندئذٍ.</li>
    <li><strong>إن رُفِض</strong>، اقرأ ملاحظة المعلّم وأعد المحاولة إن بقيت لك محاولات.</li>
  </ol>

  <div class="g-note info">
